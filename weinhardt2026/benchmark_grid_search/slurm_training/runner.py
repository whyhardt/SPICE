"""
Runner script for slurm array sweeps.
- Reads JSONL run table index by index and executes the training for that run.
- The run table is generated by run_table_generator.py and contains all the necessary information to execute 

- Get index by environment variable (SLURM_ARRAY_TASK_ID).
- Read the corresponding line from the run table JSONL file.
- Parse the JSON to get the run configuration.
- Setup specific model and execute the training with the configuration.
- Save results/metrics + status marker (success/failure).
"""

from __future__ import annotations

import argparse
import json
import os
import time
from dataclasses import dataclass
from importlib import import_module
from pathlib import Path
from typing import Any, Dict, Iterable, Optional

import numpy as np
import torch
import random


from spice import cross_entropy_loss, split_data_along_blockdim
from weinhardt2026.utils.benchmarking_gru import training as benchmark_training


# container for one run: Status, seed, losses, duration, and message (e.g. error message on failure)
@dataclass
class RunResult:
	status: str
	seed: int
	train_loss: Optional[float]
	test_loss: Optional[float]
	duration_sec: float
	message: Optional[str] = None


def _import_from_string(path: str):
	"""import a symbol from 'package.module:object' format,
		so that runner can import dataset loader functions 
		and model classes specified in the run table."""
	if ":" not in path:
		raise ValueError(f"Invalid import path '{path}'. Expected 'module:object'.")
	module_name, obj_name = path.split(":", 1)
	module = import_module(module_name)
	return getattr(module, obj_name)


def _set_seeds(seed: int) -> None:
	"""Reproducibility: 
		Set RNG seeds for python, numpy, and pytorch (CPU/GPU)."""
	random.seed(seed)
	np.random.seed(seed)
	torch.manual_seed(seed)
	if torch.cuda.is_available():
		torch.cuda.manual_seed_all(seed)


def _read_run_by_index(path: Path, index: int) -> Dict[str, Any]:
	"""reads json run table, returns row at given index"""
	with path.open("r", encoding="utf-8") as f:
		for idx, line in enumerate(f):
			if idx == index:
				return json.loads(line)
	raise IndexError(f"Run index {index} not found in {path}.")


def _read_runs_by_cfg_id(path: Path, cfg_id: str) -> list[tuple[int, Dict[str, Any]]]:
	"""reads json run table, returns all rows with a matching cfg_id"""
	matches: list[tuple[int, Dict[str, Any]]] = []
	with path.open("r", encoding="utf-8") as f:
		for idx, line in enumerate(f):
			run = json.loads(line)
			if run.get("model", {}).get("cfg_id") == cfg_id:
				matches.append((idx, run))
	if not matches:
		raise ValueError(f"cfg_id '{cfg_id}' not found in {path}.")
	return matches


def _read_run_by_cfg_id_and_replica(path: Path, cfg_id: str, replica: int) -> tuple[int, Dict[str, Any]]:
	"""reads json run table, returns the row matching both cfg_id and replicate"""
	with path.open("r", encoding="utf-8") as f:
		for idx, line in enumerate(f):
			run = json.loads(line)
			model_cfg = run.get("model", {})
			if model_cfg.get("cfg_id") == cfg_id and int(model_cfg.get("replicate", -1)) == int(replica):
				return idx, run
	raise ValueError(f"cfg_id '{cfg_id}' with replica {replica} not found in {path}.")


def _load_dataset(run: Dict[str, Any]):
	"""loads dataset according to the configuration in the run table."""
	loader = run["dataset"]["loader"]
	if loader["type"] == "entrypoint":
		fn = _import_from_string(loader["call"])
		dataset_train, dataset_test, _info = fn(**loader["kwargs"])
		return dataset_train, dataset_test

	if loader["type"] == "csv_to_dataset":
		fn = _import_from_string(loader["call"])
		dataset = fn(**loader["kwargs"])
		if run["dataset"].get("normalize_rewards", True):
			dataset.normalize_rewards()
		split = loader.get("split")
		if split:
			split_fn = _import_from_string(split["call"])
			return split_fn(dataset, **split["kwargs"])
		return dataset, None

	raise ValueError(f"Unknown loader type: {loader['type']}")


def _resolve_init_kwargs(model_cfg: Dict[str, Any], dataset_train) -> Dict[str, Any]:
	"""merges specific kwargs with dataset-derived (e.g. n_actions, n_participants, etc.)"""
	kwargs = dict(model_cfg.get("init_kwargs", {}))
	inject = model_cfg.get("inject_from_dataset", {})
	for key, expr in inject.items():
		if not expr.startswith("dataset."):
			raise ValueError(f"Unsupported inject expression: {expr}")
		attr = expr.split(".", 1)[1]
		kwargs[key] = getattr(dataset_train, attr)
	return kwargs


def _compute_loss(model: torch.nn.Module, dataset, device: torch.device) -> Optional[float]:
	"""cross-entropy loss on dataset (train/test) for reporting"""
	if dataset is None:
		return None
	model.eval()
	with torch.no_grad():
		xs = dataset.xs.to(device)
		ys = dataset.ys.to(device)
		logits, _ = model(xs)
		nan_mask = ~torch.isnan(xs[..., :model.n_actions].sum(dim=-1))
		logits = logits[nan_mask]
		labels = ys[nan_mask]
		return float(cross_entropy_loss(logits, labels).item())


def _write_status(path: Path, result: RunResult) -> None:
	"""json status file on each run"""
	payload = {
		"status": result.status,
		"seed": result.seed,
		"train_loss": result.train_loss,
		"test_loss": result.test_loss,
		"duration_sec": result.duration_sec,
		"message": result.message,
	}
	path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


def _safe_run_key(run_key: str) -> str:
	"""sanitises run_key for use in file paths (e.g. replaces '|' and '/' with safe alternatives)"""
	return run_key.replace("|", "__").replace("/", "_")


def run_one(run: Dict[str, Any], out_dir: Path, device: torch.device) -> RunResult:
	"""executes a single run end-to-end (seed, data, model, training, final loss, save model)."""
	start = time.time()
	seed = int(run["seed"])
	_set_seeds(seed)

	dataset_train, dataset_test = _load_dataset(run)
	model_cfg = run["model"]
	model_cls = _import_from_string(model_cfg["class"])
	model_kwargs = _resolve_init_kwargs(model_cfg, dataset_train)

	model = model_cls(**model_kwargs)
	model.to(device)

	opt = torch.optim.Adam(model.parameters(), lr=float(run["training"]["lr"]))

	benchmark_training(
		model=model,
		optimizer=opt,
		dataset_train=dataset_train,
		dataset_test=dataset_test,
		epochs=int(run["training"]["epochs"]),
		batch_size=run["training"].get("batch_size"),
		loss_fn=cross_entropy_loss,
		scheduler=bool(run["training"].get("scheduler", False)),
		device=device,
	)

	train_loss = _compute_loss(model, dataset_train, device)
	test_loss = _compute_loss(model, dataset_test, device)

	model_path = out_dir / "model.pt"
	torch.save(model.state_dict(), model_path)

	duration = time.time() - start
	return RunResult("ok", seed, train_loss, test_loss, duration)


def _run_and_record(run: Dict[str, Any], index: int, out_dir: Path, device: torch.device) -> RunResult:
	"""runs one entry, writes its artifacts, and records a success/failure marker."""
	run_dir = out_dir / f"{index:06d}_{_safe_run_key(run['run_key'])}"
	run_dir.mkdir(parents=True, exist_ok=True)
	(run_dir / "run.json").write_text(json.dumps(run, indent=2), encoding="utf-8")

	result_path = run_dir / "result.json"
	status_path = run_dir / "_DONE"
	fail_path = run_dir / "_FAILED"

	try:
		result = run_one(run, run_dir, device)
		_write_status(result_path, result)
		status_path.write_text("ok", encoding="utf-8")
		if fail_path.exists():
			fail_path.unlink()
		return result
	except Exception as exc:
		result = RunResult("failed", int(run["seed"]), None, None, 0.0, message=str(exc))
		_write_status(result_path, result)
		fail_path.write_text(str(exc), encoding="utf-8")
		return result


def parse_args() -> argparse.Namespace:
	p = argparse.ArgumentParser(description="Run one sweep entry from a JSONL run table.")
	p.add_argument("--run-table", default="weinhardt2026/slurm_training/json_outputs/runs.jsonl")
	p.add_argument("--index", type=int, default=None, help="Run index (overrides SLURM_ARRAY_TASK_ID)")
	p.add_argument("--cfg_id", type=str, default=None, help="Optional config ID to filter runs by (overrides index)")
	p.add_argument("--replica", type=int, default=None, help="Optional replicate number to pair with --cfg_id")
	p.add_argument("--out-dir", default="weinhardt2026/slurm_training/runs")
	p.add_argument("--device", default=None, help="cuda, cuda:0, or cpu")
	return p.parse_args()


def main() -> None:
	"""resolves index, loads the run row, creates an output folder, runs training, and writes success/failure markers"""
	args = parse_args()

	device = torch.device(args.device) if args.device else torch.device("cuda" if torch.cuda.is_available() else "cpu")

	run_table = Path(args.run_table)
	out_dir = Path(args.out_dir)
	if args.cfg_id:
		if args.replica is not None:
			index, run = _read_run_by_cfg_id_and_replica(run_table, args.cfg_id, args.replica)
			result = _run_and_record(run, index, out_dir, device)
			if result.status != "ok":
				raise RuntimeError(result.message or f"cfg_id '{args.cfg_id}' replica {args.replica} failed.")
		else:
			matches = _read_runs_by_cfg_id(run_table, args.cfg_id)
			failures: list[str] = []
			for index, run in matches:
				result = _run_and_record(run, index, out_dir, device)
				if result.status != "ok":
					failures.append(f"{index}: {result.message}")
			if failures:
				raise RuntimeError(f"One or more runs failed for cfg_id '{args.cfg_id}': {'; '.join(failures)}")
	else:
		index = args.index
		if index is None:
			env_idx = os.environ.get("SLURM_ARRAY_TASK_ID")
			if env_idx is None:
				raise RuntimeError("Missing --index and SLURM_ARRAY_TASK_ID is not set.")
			index = int(env_idx)
		run = _read_run_by_index(run_table, index)
		result = _run_and_record(run, index, out_dir, device)
		if result.status != "ok":
			raise RuntimeError(result.message or f"Run index {index} failed.")


if __name__ == "__main__":
	main()

